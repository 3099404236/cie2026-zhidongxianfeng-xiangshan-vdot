#!/usr/bin/env python3
"""Generate the data section for vdota_test.S from the golden model.

Record layout (64 bytes): old vd | vs1 | vs2 | expected vd   (16 bytes each).
Also: a 64-step accumulation chain and register-overlap expectations.
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "reference"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from gen_vdot_cases import MASK64, emit_bytes, emit_record, pack  # noqa: E402
from vdot_model import execute_vdota  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", default=str(Path(__file__).with_name("vdota_cases.inc")))
    ap.add_argument("--random", type=int, default=32)
    ap.add_argument("--seed", type=lambda s: int(s, 0), default=0xACC)
    args = ap.parse_args()
    rng = random.Random(args.seed)

    def rvec() -> int:
        return pack([rng.randint(-128, 127) for _ in range(8)], rng.getrandbits(64))

    garbage = 0xDEADBEEF_CAFEF00D_01234567 << 32       # old vd[127:32]: must not matter
    cases = [
        ("acc 0 + positive = 120", 0, pack([1, 2, 3, 4, 5, 6, 7, 8]), pack([8, 7, 6, 5, 4, 3, 2, 1])),
        ("acc 1000 + 120 (vd[127:32] garbage ignored)", garbage | 1000, pack([1, 2, 3, 4, 5, 6, 7, 8]), pack([8, 7, 6, 5, 4, 3, 2, 1])),
        ("acc -5 + negative (-204)", (2**32 - 5), pack([-1, -2, -3, -4, -5, -6, -7, -8]), pack([1, 2, 3, 4, 5, 6, 7, 8])),
        ("wrap: 0x7fffffff + 120", 0x7FFFFFFF, pack([1, 2, 3, 4, 5, 6, 7, 8]), pack([8, 7, 6, 5, 4, 3, 2, 1])),
        ("wrap: 0x80000000 + min (-130048)", 0x80000000, pack([-128] * 8), pack([127] * 8)),
        ("acc -1 + max (131072)", 2**32 - 1, pack([-128] * 8), pack([-128] * 8)),
        ("source high 64 bits ignored", 12345, pack([1, 2, 3, 4, 5, 6, 7, 8], MASK64), pack([8, 7, 6, 5, 4, 3, 2, 1], 0x0123456789ABCDEF)),
    ]
    for i in range(args.random):
        cases.append((f"random #{i}", rng.getrandbits(128), rvec(), rvec()))

    lines = ["/* AUTO-GENERATED by gen_vdota_cases.py -- do not edit. */", "  .section .rodata", "  .balign 16",
             "  .globl vdota_cases", "vdota_cases:"]
    for name, vd, a, b in cases:
        exp = execute_vdota(vd, a, b)
        signed = exp - (1 << 32) if exp & (1 << 31) else exp
        lines.append(f"  /* {name}: expected vd[31:0] = {signed} */")
        lines += [emit_bytes(vd), emit_bytes(a), emit_bytes(b), emit_bytes(exp)]
    lines += ["  .balign 8", "  .globl vdota_num_cases", "vdota_num_cases:", f"  .dword {len(cases)}", ""]

    # 64-step accumulation chain: acc = vdota(acc, A_i, B_i), acc starts at 0.
    chain = [(rvec(), rvec()) for _ in range(64)]
    acc = 0
    for a, b in chain:
        acc = execute_vdota(acc, a, b)
    lines += ["  .balign 16", "  .globl vdota_chain", "vdota_chain:"]
    for a, b in chain:
        lines += [emit_bytes(a), emit_bytes(b)]
    lines += emit_record("vdota_chain_result", f"final accumulator = {acc - (1 << 32) if acc >> 31 else acc}", acc)

    # Register overlap: vd==vs1 (old vd is P), vd==vs2 (old vd is Q), vd==v0.
    p = pack([7, -9, 11, -13, 17, -19, 23, -29], 0x5555AAAA5555AAAA)
    q = pack([-31, 37, -41, 43, -47, 53, -59, 61], 0xAAAA5555AAAA5555)
    lines += emit_record("vdota_p", "P", p)
    lines += emit_record("vdota_q", "Q", q)
    lines += emit_record("vdota_p_pq", "vdota(old=P, P, Q)", execute_vdota(p, p, q))
    lines += emit_record("vdota_q_pq", "vdota(old=Q, P, Q)", execute_vdota(q, p, q))
    lines += emit_record("vdota_m1_pq", "vdota(old=all ones, P, Q)", execute_vdota((1 << 128) - 1, p, q))
    lines.append("")
    Path(args.output).write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"wrote {len(cases)} vdota cases + 64-step chain + overlap scenarios to {args.output}")


if __name__ == "__main__":
    main()
