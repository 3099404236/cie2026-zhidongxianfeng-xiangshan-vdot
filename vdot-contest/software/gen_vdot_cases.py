#!/usr/bin/env python3
"""Generate the data section for vdot_full_test.S from the golden model.

Every record is 48 bytes:  vs1[127:0] | vs2[127:0] | expected vd[127:0]
(little-endian, exactly the layout `vle8.v`/`vse8.v` see with vl=16).

The expected values come from reference/vdot_model.py, so the bare-metal test,
NEMU and the XiangShan RTL are all checked against one executable spec.
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "reference"))

from vdot_model import execute_vdot  # noqa: E402

MASK64 = (1 << 64) - 1


def pack(values: list[int], high: int = 0) -> int:
    """Pack eight signed bytes into the low 64 bits; `high` fills bits 127:64."""
    value = (high & MASK64) << 64
    for index, item in enumerate(values):
        value |= (item & 0xFF) << (8 * index)
    return value


def directed_cases() -> list[tuple[str, int, int]]:
    noise_a = 0xDEADBEEFCAFEF00D
    noise_b = 0x0123456789ABCDEF
    return [
        ("positive [1..8].[8..1] = 120", pack([1, 2, 3, 4, 5, 6, 7, 8]), pack([8, 7, 6, 5, 4, 3, 2, 1])),
        ("negative [-1..-8].[1..8] = -204", pack([-1, -2, -3, -4, -5, -6, -7, -8]), pack([1, 2, 3, 4, 5, 6, 7, 8])),
        ("max: 8*(-128*-128) = 131072", pack([-128] * 8), pack([-128] * 8)),
        ("8*(127*127) = 129032", pack([127] * 8), pack([127] * 8)),
        ("min: 8*(-128*127) = -130048", pack([-128] * 8), pack([127] * 8)),
        ("zero vector", pack([0] * 8), pack([-128, 127, -1, 1, 55, -55, 100, -100])),
        ("mixed boundaries", pack([-128, 127, 0, 1, -1, 64, -64, 0]), pack([127, -128, 5, -1, 1, -64, 64, 0])),
        ("only lane 7: -128*-128", pack([0, 0, 0, 0, 0, 0, 0, -128]), pack([0, 0, 0, 0, 0, 0, 0, -128])),
        ("only lane 0: -1*-1", pack([-1, 0, 0, 0, 0, 0, 0, 0]), pack([-1, 0, 0, 0, 0, 0, 0, 0])),
        ("alternating signs", pack([1, -1] * 4), pack([-1, 1] * 4)),
        ("all -1 . all -1 = 8", pack([-1] * 8), pack([-1] * 8)),
        ("high 64 bits are ignored", pack([1, 2, 3, 4, 5, 6, 7, 8], noise_a), pack([8, 7, 6, 5, 4, 3, 2, 1], noise_b)),
        ("high 64 bits all ones", pack([-128] * 8, MASK64), pack([127] * 8, MASK64)),
    ]


def random_cases(count: int, seed: int) -> list[tuple[str, int, int]]:
    rng = random.Random(seed)
    cases = []
    for index in range(count):
        lhs = [rng.randint(-128, 127) for _ in range(8)]
        rhs = [rng.randint(-128, 127) for _ in range(8)]
        cases.append((f"random #{index}", pack(lhs, rng.getrandbits(64)), pack(rhs, rng.getrandbits(64))))
    return cases


def emit_bytes(value: int) -> str:
    return "  .byte " + ", ".join(f"0x{(value >> (8 * i)) & 0xFF:02x}" for i in range(16))


def emit_record(label: str, comment: str, value: int) -> list[str]:
    return [f"{label}:  /* {comment} */", emit_bytes(value)]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("-o", "--output", default=str(Path(__file__).with_name("vdot_cases.inc")))
    parser.add_argument("--random", type=int, default=48)
    parser.add_argument("--seed", type=lambda s: int(s, 0), default=0x2026)
    args = parser.parse_args()

    cases = directed_cases() + random_cases(args.random, args.seed)
    lines = [
        "/* AUTO-GENERATED by gen_vdot_cases.py -- do not edit. */",
        "  .section .rodata",
        "  .balign 16",
        "  .globl vdot_cases",
        "vdot_cases:",
    ]
    for name, vs1, vs2 in cases:
        vd = execute_vdot(vs1, vs2)
        signed = vd - (1 << 32) if vd & (1 << 31) else vd
        lines.append(f"  /* {name}: expected vd[31:0] = {signed} */")
        lines.append(emit_bytes(vs1))
        lines.append(emit_bytes(vs2))
        lines.append(emit_bytes(vd))
    lines += ["  .balign 8", "  .globl vdot_num_cases", "vdot_num_cases:", f"  .dword {len(cases)}", ""]

    # Back-to-back RAW/WAW scenario (see vdot_full_test.S, `chain_test`):
    #   v10 = vdot(A, B1); v11 = vdot(v10, B2); v10 = vdot(v11, B3)
    rng = random.Random(args.seed + 1)
    a = pack([rng.randint(-128, 127) for _ in range(8)], rng.getrandbits(64))
    b1 = pack([rng.randint(-128, 127) for _ in range(8)], rng.getrandbits(64))
    b2 = pack([rng.randint(-128, 127) for _ in range(8)], rng.getrandbits(64))
    b3 = pack([rng.randint(-128, 127) for _ in range(8)], rng.getrandbits(64))
    r1 = execute_vdot(a, b1)
    r2 = execute_vdot(r1, b2)
    r3 = execute_vdot(r2, b3)
    lines += ["  .balign 16"]
    lines += emit_record("chain_a", "A", a)
    lines += emit_record("chain_b1", "B1", b1)
    lines += emit_record("chain_b2", "B2", b2)
    lines += emit_record("chain_b3", "B3", b3)
    lines += emit_record("chain_r2", f"expected v11 = vdot(vdot(A,B1),B2) = {r2}", r2)
    lines += emit_record("chain_r3", f"expected v10 = vdot(v11,B3) = {r3}", r3)

    # Register-overlap scenario: vd == vs1, vd == vs2, vs1 == vs2, vd == v0.
    p = pack([7, -9, 11, -13, 17, -19, 23, -29], 0x5555AAAA5555AAAA)
    q = pack([-31, 37, -41, 43, -47, 53, -59, 61], 0xAAAA5555AAAA5555)
    lines += emit_record("ovl_p", "P", p)
    lines += emit_record("ovl_q", "Q", q)
    lines += emit_record("ovl_pq", f"vdot(P,Q) = {execute_vdot(p, q)}", execute_vdot(p, q))
    lines += emit_record("ovl_pp", f"vdot(P,P) = {execute_vdot(p, p)}", execute_vdot(p, p))
    lines.append("")

    Path(args.output).write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"wrote {len(cases)} cases + chain/overlap scenarios to {args.output}")


if __name__ == "__main__":
    main()
