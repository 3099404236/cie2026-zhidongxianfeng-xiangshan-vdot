#!/usr/bin/env python3
"""Assemble the public contest repository from the working folders.

  python vdot-contest/tools/make_public_repo.py [DEST]     (default: 香山/cie2026-repo)

Copies the deliverables of vdot-submission/ and vdot-contest/ with the same
relative layout (the documents refer to these paths), leaves out working files
that are not part of the submission (handover notes, progress report, the
plain-text submission form, zip packages, build outputs, caches), writes the
top-level README.md and a .gitignore. DEST is rebuilt from scratch, but only if
it is empty or was created by this script (marker file .cie2026-repo).
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]          # .../香山
SUB = ROOT / "vdot-submission"
CON = ROOT / "vdot-contest"
DEST = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "cie2026-repo"
MARKER = ".cie2026-repo"

SKIP_DIRS = {"__pycache__", "build", "gen", "out", "packages", ".git"}
SKIP_FILES = {
    SUB / "AI_HANDOVER_VDOT.md",           # notes for the next maintainer
    SUB / "PROGRESS_REPORT.md",            # internal progress report
    SUB / "my_submission.txt",             # contact details: only submitted encrypted
    SUB / "docs" / "演示视频录制脚本.md",    # recording notes for the author
    CON / "tools" / "public_repo_README.md",
}
SKIP_SUFFIX = {".pyc", ".o", ".elf", ".zip"}

GITIGNORE = """\
.cie2026-repo
__pycache__/
*.pyc
build/
out/
rtl-explore/gen/
*.o
*.elf
"""


def copy_tree(src: Path, dst: Path) -> int:
    n = 0
    for p in sorted(src.rglob("*")):
        rel = p.relative_to(src)
        if not p.is_file() or any(part in SKIP_DIRS for part in rel.parts):
            continue
        if p in SKIP_FILES or p.suffix in SKIP_SUFFIX:
            continue
        q = dst / rel
        q.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, q)
        n += 1
    return n


def fix(path: Path, old: str, new: str) -> None:
    text = path.read_text(encoding="utf-8")
    if old not in text:
        raise SystemExit(f"{path}: expected text not found: {old[:60]!r}")
    path.write_text(text.replace(old, new), encoding="utf-8", newline="\n")


def main() -> None:
    if DEST.exists():
        if any(DEST.iterdir()) and not (DEST / MARKER).exists():
            raise SystemExit(f"{DEST} exists and was not created by this script; not touching it")
        shutil.rmtree(DEST)
    DEST.mkdir(parents=True)
    (DEST / MARKER).write_text("generated by vdot-contest/tools/make_public_repo.py\n")
    n = copy_tree(SUB, DEST / "vdot-submission") + copy_tree(CON, DEST / "vdot-contest")
    shutil.copy2(CON / "tools" / "public_repo_README.md", DEST / "README.md")
    (DEST / ".gitignore").write_text(GITIGNORE, newline="\n")

    # references to files that stay in the working folders
    fix(DEST / "vdot-submission" / "README.md",
        "├── README.md / PROGRESS_REPORT.md / AI_HANDOVER_VDOT.md", "├── README.md")
    logs_readme = DEST / "vdot-submission" / "logs" / "README.md"
    lines = logs_readme.read_text(encoding="utf-8").splitlines(keepends=True)
    logs_readme.write_text("".join(l for l in lines if "verification_logs.txt" not in l), encoding="utf-8")

    files = [p for p in DEST.rglob("*") if p.is_file()]
    size = sum(p.stat().st_size for p in files)
    print(f"{DEST}: {len(files)} files ({n} copied), {size / 1e6:.1f} MB")
    for p in sorted(files, key=lambda p: -p.stat().st_size)[:5]:
        print(f"  {p.stat().st_size / 1e6:7.2f} MB  {p.relative_to(DEST)}")


if __name__ == "__main__":
    main()
